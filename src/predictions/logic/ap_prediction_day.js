/**
 * Get Day prediction by day of week index (0=Sunday … 6=Saturday)
 * or by day name string.
 *
 * @param {number|string} dayInput - Day index (0-6) or name e.g. "Sunday"
 * @returns {object|null}
 */
window.AP_PREDICTION_DAY.get = function(dayInput) {
  if (typeof dayInput === 'number') {
    return this[dayInput] || null;
  }
  if (typeof dayInput === 'string') {
    const names = ['sunday','monday','tuesday','wednesday','thursday','friday','saturday'];
    const idx = names.indexOf(dayInput.toLowerCase());
    if (idx >= 0) return this[idx] || null;
    // Search by Hindi name
    for (let i = 0; i <= 6; i++) {
      if (this[i] && this[i].name_hi === dayInput) return this[i];
    }
  }
  return null;
};
