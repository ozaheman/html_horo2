window.AP_PREDICTION_YOGA.get = function(input) {
  if (typeof input === 'number') {
    return this[input] || null;
  }
  if (typeof input === 'string') {
    const lower = input.toLowerCase().trim();
    const enIdx = this.YOGA_NAMES.findIndex(n => n && n.toLowerCase() === lower);
    if (enIdx > 0) return this[enIdx] || null;
    const hiIdx = this.YOGA_NAMES_HI.findIndex(n => n && n === input.trim());
    if (hiIdx > 0) return this[hiIdx] || null;
  }
  return null;
};
